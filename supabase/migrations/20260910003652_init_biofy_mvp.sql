create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  display_name text,
  avatar_url text,
  bio text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (
    username is null or (
      username = lower(username)
      and username ~ '^[a-z0-9][a-z0-9._-]{2,29}$'
      and username not in (
        'admin','api','auth','login','signup','dashboard','settings','onboarding',
        'pricing','templates','support','help','biofy'
      )
    )
  )
);

create unique index profiles_username_lower_idx
  on public.profiles(lower(username))
  where username is not null;

create table public.public_profiles (
  username text primary key,
  display_name text,
  avatar_url text,
  bio text,
  updated_at timestamptz not null default now()
);

create table public.pages (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  username text unique,
  template text not null default 'minimal',
  theme jsonb not null default '{}'::jsonb,
  is_published boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index pages_public_username_idx
  on public.pages(username)
  where is_published = true;

create table public.page_blocks (
  id uuid primary key default gen_random_uuid(),
  page_id uuid not null references public.pages(id) on delete cascade,
  type text not null default 'link',
  title text,
  url text,
  config jsonb not null default '{}'::jsonb,
  position integer not null default 0 check (position >= 0),
  is_visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index page_blocks_page_position_idx
  on public.page_blocks(page_id, position);

create table public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  plan text not null default 'free' check (plan in ('free','pro','business')),
  status text not null default 'active',
  interval text not null default 'monthly',
  current_period_end timestamptz,
  cancel_at_period_end boolean not null default false,
  stripe_customer_id text,
  stripe_subscription_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.analytics_events (
  id bigint generated by default as identity primary key,
  page_id uuid not null references public.pages(id) on delete cascade,
  block_id uuid references public.page_blocks(id) on delete set null,
  kind text not null check (kind in ('view','click')),
  referrer text,
  created_at timestamptz not null default now()
);

create index analytics_events_page_created_idx
  on public.analytics_events(page_id, created_at desc);

create index analytics_events_block_created_idx
  on public.analytics_events(block_id, created_at desc)
  where block_id is not null;

