create or replace function private.sync_public_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.username is not null then
      delete from public.public_profiles where username = old.username;
    end if;
    return old;
  end if;

  if tg_op = 'UPDATE'
     and old.username is not null
     and old.username is distinct from new.username then
    delete from public.public_profiles where username = old.username;
  end if;

  if new.username is not null then
    insert into public.public_profiles (username, display_name, avatar_url, bio, updated_at)
    values (new.username, new.display_name, new.avatar_url, new.bio, now())
    on conflict (username) do update set
      display_name = excluded.display_name,
      avatar_url = excluded.avatar_url,
      bio = excluded.bio,
      updated_at = excluded.updated_at;
  end if;

  update public.pages set username = new.username where user_id = new.id;
  return new;
end;
$$;

revoke all on function private.sync_public_profile() from public;

create trigger profiles_sync_public
  after insert or update or delete on public.profiles
  for each row execute function private.sync_public_profile();

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, avatar_url)
  values (
    new.id,
    coalesce(
      new.raw_user_meta_data->>'display_name',
      new.raw_user_meta_data->>'full_name',
      split_part(new.email, '@', 1)
    ),
    new.raw_user_meta_data->>'avatar_url'
  )
  on conflict (id) do nothing;

  insert into public.pages (user_id)
  values (new.id)
  on conflict (user_id) do nothing;

  insert into public.subscriptions (user_id)
  values (new.id)
  on conflict (user_id) do nothing;

  return new;
end;
$$;

revoke all on function private.handle_new_user() from public;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

create or replace function public.is_username_available(candidate text)
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select
    candidate = lower(candidate)
    and candidate ~ '^[a-z0-9][a-z0-9._-]{2,29}$'
    and candidate not in (
      'admin','api','auth','login','signup','dashboard','settings','onboarding',
      'pricing','templates','support','help','biofy'
    )
    and not exists (
      select 1
      from public.public_profiles
      where username = candidate
    );
$$;

revoke all on function public.is_username_available(text) from public;
grant execute on function public.is_username_available(text) to anon, authenticated;
